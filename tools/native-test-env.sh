set -euo pipefail

libs="${FCAD_OCCT_LIB_DIR:-}:$PWD/vendor/planegcs"
case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*)
    export PATH="$libs:$PATH"
    if [ -n "${VCToolsInstallDir:-}" ]; then
      export PATH="$(cygpath -u "$VCToolsInstallDir")bin/Hostx64/x64:$PATH"
    fi ;;
  Darwin) export DYLD_LIBRARY_PATH="$libs" DYLD_FALLBACK_LIBRARY_PATH="$libs" ;;
