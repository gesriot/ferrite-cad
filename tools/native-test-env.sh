  directory="$artifact_root/$producer"
  mkdir -p "$directory"
  if command -v cygpath >/dev/null 2>&1; then directory="$(cygpath -w "$directory")"; fi
  export "$producer=$directory"
  if [ "$consumer" != - ]; then export "$consumer=$directory${file#-}"; fi
